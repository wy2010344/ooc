export const numDef = {
  '+'(a: number, b: number) {
    return a + b
  },
  '-'(a: number, b: number) {
    return a - b
  },
  '*'(a: number, b: number) {
    return a * b
  },
  'div'(a: number, b: number) {
    return a / b
  },
  '%'(a: number, b: number) {
    return a % b
  },
  '>'(a: number, b: number) {
    return a > b
  },
  '<'(a: number, b: number) {
    return a < b
  },
  '>='(a: number, b: number) {
    return a >= b
  },
  '<='(a: number, b: number) {
    return a <= b
  },
}
